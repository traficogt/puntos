#!/usr/bin/env node
/* eslint-disable security/detect-non-literal-fs-filename -- Reads and rewrites only repository files under public/. */
/**
 * Content-derived asset versions for the hand-written pages.
 *
 *   npm run sw:build   runs this first, then regenerates public/sw.js
 *   npm run sw:check   exit 1 when a page or stylesheet carries stale versions
 *   node src/scripts/build-asset-versions.mjs [--check] [--report]
 *
 * Every local asset reference in the hand-written HTML under public/ (<script src>,
 * <link href> for stylesheets, icons, the manifest and preloads, <img>/<source> src and
 * srcset, <video> src/poster, <audio> src) is rewritten to `?v=<hash>`, where hash is
 * the first eight hex digits of the SHA-256 of the referenced file. Stylesheets receive
 * the same treatment for their `url()` and `@import` references (fonts, images, imported
 * sheets). A stylesheet's own hash is taken over its rewritten content, so the rewrite
 * runs leaf first: fonts -> stylesheets -> pages. An existing `?v=...` is replaced, other
 * query parameters and fragments are preserved, and everything outside the rewritten
 * attribute values stays byte for byte.
 *
 * A reference is left alone when it is external (any scheme, `//` or `#`), points at
 * /api, at a document (.html), at the service worker, or at a path that is not a file
 * under public/ (for example the dynamic /runtime-config.js), and when it sits inside an
 * HTML comment, a <script> or <style> body, or a CSS comment. Generated trees are never
 * touched: see EXCLUDED_DIRECTORIES.
 *
 * JavaScript sources are never rewritten. Assets that scripts request by string literal
 * stay unversioned and rely on the service worker's network-first strategy;
 * RUNTIME_REFERENCED_ASSETS documents them.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_PATH = fs.realpathSync(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = path.resolve(path.dirname(SCRIPT_PATH), "..", "..");

export const VERSION_PARAM = "v";
export const HASH_LENGTH = 8;
export const VERSION_PATTERN = /^[0-9a-f]{8}$/;

/**
 * Trees under public/ that are build output or generated by other tooling. They keep
 * whatever versioning their own build applies.
 *   merchant/        Vite output of web/merchant (template web/merchant/index.html;
 *                    recursos/ is content-hashed by Vite)
 *   revision-astryx/ illustration review export
 *   ayuda/           help site built by help/scripts
 *   pwa-test/        manual PWA test harness
 * @type {string[]}
 */
export const EXCLUDED_DIRECTORIES = ["merchant", "revision-astryx", "ayuda", "pwa-test"];

/**
 * Assets requested from JavaScript by string literal. Their URLs live in .js sources,
 * which this script never rewrites, so they stay unversioned and are served with the
 * default `public, max-age=0` revalidation; the service worker handles them
 * network-first. Listed here so nobody wonders why they carry no `?v=`.
 * @type {Array<{ asset: string, source: string }>}
 */
export const RUNTIME_REFERENCED_ASSETS = [
  { asset: "/styles/demand-notebook.css", source: "public/demand-notebook.js (link.href)" },
  {
    asset: "/admin-dashboard/fragments/*.html",
    source: "public/admin-dashboard/layout.js (fetch of 14 tab fragments)",
  },
  { asset: "/runtime-config.js", source: "src/app/server.js (dynamic route, no-store)" },
  {
    asset: "/icon-192.png, /icon-512.png, /icon.svg",
    source: "public/manifest.webmanifest icons (JSON, not rewritten)",
  },
  {
    asset: 'ES module imports (import "./x.js")',
    source: "every public/**/*.js module graph; entry <script src> tags are versioned",
  },
  {
    asset: "/icon.svg?v=4, /styles/fonts.css, /styles/marketing.css?v=4, /guides/guides.css?v=3",
    source: "src/content/guides/render.js (server-rendered /guias pages, served no-store)",
  },
  {
    asset: "/icon-192.png?v=2, /pf-email-wordmark.png?v=2, /pf-email-lockup.png?v=2",
    source: "src/app/services/messaging/email-branding.js (e-mail images)",
  },
];

const ORIGIN = "https://asset-versions.invalid";
const SKIPPED_SCHEMES = /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i;

/**
 * `<link rel>` values whose href names a local asset. Shared with the service worker
 * generator so both tools agree on what a page requests.
 */
export const LINK_RELS = new Set([
  "stylesheet",
  "icon",
  "shortcut icon",
  "apple-touch-icon",
  "apple-touch-icon-precomposed",
  "mask-icon",
  "manifest",
  "modulepreload",
  "preload",
]);

/**
 * Request paths that never receive a version even when they name a file:
 * API responses, documents (navigations keep stable URLs) and the worker itself.
 * @type {RegExp[]}
 */
const UNVERSIONED_PATH_PATTERNS = [/^\/api(?:\/|$)/i, /\.html?$/i, /^\/sw\.js$/i];

/** Attribute name -> value, quoted or bare. */
const ATTRIBUTE = /([A-Za-z][\w:-]*)(\s*=\s*)(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))/g;
/** HTML comments, whole <script>/<style> elements, or one asset tag. */
const HTML_SEGMENT =
  /<!--[\s\S]*?-->|<script\b[^>]*>[\s\S]*?<\/script\s*>|<style\b[^>]*>[\s\S]*?<\/style\s*>|<(?:script|link|img|source|video|audio)\b[^>]*>/gi;
/** CSS comments, url() references, or quoted `@import` targets. */
const CSS_SEGMENT =
  /\/\*[\s\S]*?\*\/|url\(\s*(?:"[^"]*"|'[^']*'|[^)"'\s][^)]*)\s*\)|@import\s+(?:"[^"]*"|'[^']*')/gi;

/** @type {Record<string, string[]>} tag name -> attributes that name assets */
const ASSET_ATTRIBUTES = {
  script: ["src"],
  img: ["src", "srcset"],
  source: ["src", "srcset"],
  video: ["src", "poster"],
  audio: ["src"],
  link: ["href"],
};

/** @param {string} value */
function compare(value, other) {
  return value < other ? -1 : value > other ? 1 : 0;
}

/** @param {Buffer | string} bytes */
export function contentHash(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex").slice(0, HASH_LENGTH);
}

/** @param {string} pathname */
function isVersionablePath(pathname) {
  return !UNVERSIONED_PATH_PATTERNS.some((pattern) => pattern.test(pathname));
}

/**
 * @typedef {"versioned" | "external" | "excluded" | "unresolved"} ReferenceStatus
 */

/**
 * @typedef {(pathname: string) => string} HashFor
 *   Content hash of the file served at a site-root path, or "" when no such file exists.
 */

/**
 * Rewrite one reference as written in a page or stylesheet.
 * @param {string} reference
 * @param {string} basePathname site path of the referencing file
 * @param {HashFor} hashFor
 * @returns {{ value: string, status: ReferenceStatus }}
 */
export function resolveReference(reference, basePathname, hashFor) {
  const leading = /^\s*/.exec(reference)?.[0] ?? "";
  const trailing = /\s*$/.exec(reference)?.[0] ?? "";
  const trimmed = reference.trim();
  if (!trimmed || SKIPPED_SCHEMES.test(trimmed)) {
    return { value: reference, status: "external" };
  }
  let url;
  try {
    url = new URL(trimmed, `${ORIGIN}${basePathname}`);
  } catch {
    return { value: reference, status: "external" };
  }
  if (url.origin !== ORIGIN) return { value: reference, status: "external" };
  if (!isVersionablePath(url.pathname)) return { value: reference, status: "excluded" };
  const hash = hashFor(url.pathname);
  if (!hash) return { value: reference, status: "unresolved" };

  // Rebuild from the original text so relative paths and escaping stay as written.
  const fragmentIndex = trimmed.indexOf("#");
  const withoutFragment = fragmentIndex < 0 ? trimmed : trimmed.slice(0, fragmentIndex);
  const fragment = fragmentIndex < 0 ? "" : trimmed.slice(fragmentIndex);
  const queryIndex = withoutFragment.indexOf("?");
  const pathPart = queryIndex < 0 ? withoutFragment : withoutFragment.slice(0, queryIndex);
  const query = queryIndex < 0 ? "" : withoutFragment.slice(queryIndex + 1);
  const params = query
    .split("&")
    .filter((param) => param && !new RegExp(`^${VERSION_PARAM}(?:=|$)`).test(param));
  params.push(`${VERSION_PARAM}=${hash}`);
  return {
    value: `${leading}${pathPart}?${params.join("&")}${fragment}${trailing}`,
    status: "versioned",
  };
}

/**
 * The reference with its `?v=` refreshed, or unchanged when it is left alone.
 * @param {string} reference
 * @param {string} basePathname
 * @param {HashFor} hashFor
 */
export function versionReference(reference, basePathname, hashFor) {
  return resolveReference(reference, basePathname, hashFor).value;
}

/**
 * @typedef {object} RewriteResult
 * @property {string} source
 * @property {number} versioned Number of references that now carry a version.
 * @property {string[]} unresolved Local references that name no file under public/.
 */

/**
 * @param {string} value srcset attribute
 * @param {(reference: string) => string} rewrite
 */
function rewriteSrcset(value, rewrite) {
  return value.replace(/(^|,)(\s*)([^\s,]+)/g, (_match, separator, space, url) => {
    return `${separator}${space}${rewrite(url)}`;
  });
}

/**
 * Version the asset attributes of one opening tag.
 * @param {string} tag
 * @param {string} basePathname
 * @param {HashFor} hashFor
 * @param {RewriteResult} result
 */
function rewriteTag(tag, basePathname, hashFor, result) {
  const name = (/^<([a-z]+)/i.exec(tag)?.[1] || "").toLowerCase();
  const attributeNames = ASSET_ATTRIBUTES[name];
  if (!attributeNames) return tag;
  if (name === "link") {
    /** @type {Record<string, string>} */
    const attributes = {};
    for (const attribute of tag.matchAll(ATTRIBUTE)) {
      attributes[attribute[1].toLowerCase()] = attribute[3] ?? attribute[4] ?? attribute[5] ?? "";
    }
    const rels = (attributes.rel || "").toLowerCase().split(/\s+/).filter(Boolean);
    if (!rels.some((rel) => LINK_RELS.has(rel)) && !LINK_RELS.has(rels.join(" "))) return tag;
  }
  /** @param {string} reference */
  const rewrite = (reference) => {
    const resolved = resolveReference(reference, basePathname, hashFor);
    if (resolved.status === "versioned") result.versioned += 1;
    else if (resolved.status === "unresolved") result.unresolved.push(reference.trim());
    return resolved.value;
  };
  return tag.replace(
    ATTRIBUTE,
    (match, attributeName, equals, doubleQuoted, singleQuoted, bare) => {
      const lower = attributeName.toLowerCase();
      if (!attributeNames.includes(lower)) return match;
      const value = doubleQuoted ?? singleQuoted ?? bare ?? "";
      const next = lower === "srcset" ? rewriteSrcset(value, rewrite) : rewrite(value);
      if (next === value) return match;
      if (doubleQuoted !== undefined) return `${attributeName}${equals}"${next}"`;
      if (singleQuoted !== undefined) return `${attributeName}${equals}'${next}'`;
      return `${attributeName}${equals}${next}`;
    },
  );
}

/**
 * Version the local asset references of an HTML document. Comments and the bodies of
 * <script> and <style> elements are returned untouched.
 * @param {string} source
 * @param {string} pathname site path of the document (for relative references)
 * @param {HashFor} hashFor
 * @returns {RewriteResult}
 */
export function rewriteHtml(source, pathname, hashFor) {
  /** @type {RewriteResult} */
  const result = { source: "", versioned: 0, unresolved: [] };
  result.source = source.replace(HTML_SEGMENT, (segment) => {
    if (segment.startsWith("<!--") || /^<style/i.test(segment)) return segment;
    if (/^<script/i.test(segment)) {
      const opening = /^<script\b[^>]*>/i.exec(segment)?.[0] || "";
      return `${rewriteTag(opening, pathname, hashFor, result)}${segment.slice(opening.length)}`;
    }
    return rewriteTag(segment, pathname, hashFor, result);
  });
  return result;
}

/**
 * Version the `url()` and quoted `@import` references of a stylesheet. Comments are
 * returned untouched.
 * @param {string} source
 * @param {string} pathname site path of the stylesheet
 * @param {HashFor} hashFor
 * @returns {RewriteResult}
 */
export function rewriteCss(source, pathname, hashFor) {
  /** @type {RewriteResult} */
  const result = { source: "", versioned: 0, unresolved: [] };
  /** @param {string} reference */
  const rewrite = (reference) => {
    const resolved = resolveReference(reference, pathname, hashFor);
    if (resolved.status === "versioned") result.versioned += 1;
    else if (resolved.status === "unresolved") result.unresolved.push(reference.trim());
    return resolved.value;
  };
  result.source = source.replace(CSS_SEGMENT, (segment) => {
    if (segment.startsWith("/*")) return segment;
    const url = /^(url\(\s*)(["']?)([\s\S]*?)\2(\s*\))$/i.exec(segment);
    if (url) return `${url[1]}${url[2]}${rewrite(url[3])}${url[2]}${url[4]}`;
    const imported = /^(@import\s+)(["'])([^"']*)\2$/i.exec(segment);
    if (imported) return `${imported[1]}${imported[2]}${rewrite(imported[3])}${imported[2]}`;
    return segment;
  });
  return result;
}

/**
 * @param {string} publicDir
 * @returns {{ pages: string[], stylesheets: string[] }} absolute paths, sorted
 */
export function listVersionedFiles(publicDir) {
  /** @type {string[]} */
  const pages = [];
  /** @type {string[]} */
  const stylesheets = [];
  /** @param {string} directory */
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const file = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        const relative = path.relative(publicDir, file).split(path.sep).join("/");
        if (EXCLUDED_DIRECTORIES.includes(relative) || entry.name === "node_modules") continue;
        walk(file);
        continue;
      }
      if (!entry.isFile()) continue;
      const lower = entry.name.toLowerCase();
      if (lower.endsWith(".html") || lower.endsWith(".htm")) pages.push(file);
      else if (lower.endsWith(".css") && !lower.endsWith(".min.css")) {
        // Vendored stylesheets are shipped as published; their URLs are versioned by the pages.
        if (!file.split(path.sep).includes("vendor")) stylesheets.push(file);
      }
    }
  };
  walk(publicDir);
  return { pages: pages.sort(compare), stylesheets: stylesheets.sort(compare) };
}

/**
 * @typedef {object} VersionedFile
 * @property {string} file Absolute path.
 * @property {string} relativePath Path relative to the repository root, with forward slashes.
 * @property {string} pathname Site path.
 * @property {string} currentSource Content on disk.
 * @property {string} source Content with refreshed versions.
 * @property {boolean} fresh Whether disk already matches.
 * @property {number} versioned Number of versioned references.
 * @property {string[]} unresolved Local references that name no file under public/.
 */

/**
 * @typedef {object} VersionOptions
 * @property {string} [rootDir] Repository root (defaults to the checkout containing this script).
 */

/**
 * @typedef {object} VersionResult
 * @property {string} publicDir
 * @property {VersionedFile[]} stylesheets
 * @property {VersionedFile[]} pages
 * @property {VersionedFile[]} files Stylesheets first, then pages.
 * @property {VersionedFile[]} stale Files whose content on disk differs from the rewrite.
 * @property {boolean} fresh
 * @property {string[]} summary One line per stale file.
 * @property {number} versioned Total versioned references.
 * @property {Map<string, string>} hashes Site path -> hash for every versioned target.
 * @property {string[]} cycles Stylesheets whose imports form a cycle (left unversioned).
 */

/**
 * Compute the versioned content of every hand-written page and stylesheet.
 * @param {VersionOptions} [options]
 * @returns {VersionResult}
 */
export function buildAssetVersions(options = {}) {
  const rootDir = options.rootDir || DEFAULT_ROOT;
  const publicDir = path.join(rootDir, "public");
  const listed = listVersionedFiles(publicDir);
  const stylesheetSet = new Set(listed.stylesheets);

  /** @param {string} file */
  const pathnameOf = (file) =>
    `/${path.relative(publicDir, file).split(path.sep).map(encodeURIComponent).join("/")}`;
  /** @param {string} file */
  const relativeOf = (file) => path.relative(rootDir, file).split(path.sep).join("/");

  /** @param {string} pathname */
  const fileFor = (pathname) => {
    let decoded;
    try {
      decoded = decodeURIComponent(pathname);
    } catch {
      return "";
    }
    const file = path.join(publicDir, decoded);
    const relative = path.relative(publicDir, file);
    if (!relative || relative.startsWith("..") || path.isAbsolute(relative)) return "";
    let stat;
    try {
      stat = fs.statSync(file);
    } catch {
      return "";
    }
    return stat.isFile() ? file : "";
  };

  /** @type {Map<string, string>} file -> hash */
  const hashByFile = new Map();
  /** @type {Map<string, string>} pathname -> hash */
  const hashes = new Map();
  /** @type {Map<string, RewriteResult & { currentSource: string }>} */
  const rewrittenStylesheets = new Map();
  const inProgress = new Set();
  /** @type {string[]} */
  const cycles = [];

  /** @param {string} file */
  function rewrittenStylesheet(file) {
    let rewritten = rewrittenStylesheets.get(file);
    if (!rewritten) {
      const currentSource = fs.readFileSync(file, "utf8");
      rewritten = { currentSource, ...rewriteCss(currentSource, pathnameOf(file), hashFor) };
      rewrittenStylesheets.set(file, rewritten);
    }
    return rewritten;
  }

  /** @type {HashFor} */
  function hashFor(pathname) {
    const file = fileFor(pathname);
    if (!file) return "";
    const known = hashByFile.get(file);
    if (known) return known;
    if (inProgress.has(file)) {
      cycles.push(relativeOf(file));
      return "";
    }
    inProgress.add(file);
    const bytes = stylesheetSet.has(file)
      ? Buffer.from(rewrittenStylesheet(file).source, "utf8")
      : fs.readFileSync(file);
    inProgress.delete(file);
    const hash = contentHash(bytes);
    hashByFile.set(file, hash);
    hashes.set(pathnameOf(file), hash);
    return hash;
  }

  /** @type {VersionedFile[]} */
  const stylesheets = listed.stylesheets.map((file) => {
    const rewritten = rewrittenStylesheet(file);
    return {
      file,
      relativePath: relativeOf(file),
      pathname: pathnameOf(file),
      currentSource: rewritten.currentSource,
      source: rewritten.source,
      fresh: rewritten.source === rewritten.currentSource,
      versioned: rewritten.versioned,
      unresolved: rewritten.unresolved,
    };
  });
  /** @type {VersionedFile[]} */
  const pages = listed.pages.map((file) => {
    const currentSource = fs.readFileSync(file, "utf8");
    const rewritten = rewriteHtml(currentSource, pathnameOf(file), hashFor);
    return {
      file,
      relativePath: relativeOf(file),
      pathname: pathnameOf(file),
      currentSource,
      source: rewritten.source,
      fresh: rewritten.source === currentSource,
      versioned: rewritten.versioned,
      unresolved: rewritten.unresolved,
    };
  });

  const files = [...stylesheets, ...pages];
  const stale = files.filter((entry) => !entry.fresh);
  return {
    publicDir,
    stylesheets,
    pages,
    files,
    stale,
    fresh: stale.length === 0,
    summary: stale.map((entry) => `${entry.relativePath} (${entry.versioned} references)`),
    versioned: files.reduce((total, entry) => total + entry.versioned, 0),
    hashes,
    cycles: [...new Set(cycles)].sort(compare),
  };
}

/**
 * Report whether every page and stylesheet carries current versions.
 * @param {VersionOptions} [options]
 */
export function checkAssetVersions(options = {}) {
  return buildAssetVersions(options);
}

/**
 * Rewrite the pages and stylesheets whose versions are stale.
 * @param {VersionOptions} [options]
 */
export function writeAssetVersions(options = {}) {
  const result = buildAssetVersions(options);
  for (const entry of result.stale) fs.writeFileSync(entry.file, entry.source);
  return result;
}

function main() {
  const args = new Set(process.argv.slice(2));
  if (args.has("--help") || args.has("-h")) {
    console.log(
      "Usage: node src/scripts/build-asset-versions.mjs [--check] [--report]\n" +
        "  (no flag)  rewrite ?v=<content hash> on local asset references in public/ pages and stylesheets\n" +
        "  --check    exit 1 listing the files whose versions are stale\n" +
        "  --report   print every file with its reference count and the runtime-only assets",
    );
    return;
  }
  if (args.has("--report")) {
    const result = checkAssetVersions();
    console.log(
      `${result.files.length} files, ${result.versioned} versioned references, ${result.hashes.size} hashed assets`,
    );
    for (const entry of result.files) {
      const state = entry.fresh ? "" : "  (stale)";
      console.log(`  ${entry.relativePath}: ${entry.versioned}${state}`);
      for (const reference of entry.unresolved) console.log(`    unresolved ${reference}`);
    }
    for (const cycle of result.cycles) console.log(`  cycle: ${cycle}`);
    console.log("\nRuntime-referenced assets left unversioned:");
    for (const entry of RUNTIME_REFERENCED_ASSETS) {
      console.log(`  ${entry.asset}\n    ${entry.source}`);
    }
    return;
  }
  if (args.has("--check")) {
    const result = checkAssetVersions();
    if (result.fresh) {
      console.log(
        `asset versions are up to date (${result.versioned} references in ${result.files.length} files)`,
      );
      return;
    }
    console.error(
      `${result.stale.length} file(s) carry stale asset versions. Run: npm run sw:build`,
    );
    for (const line of result.summary) console.error(`  ${line}`);
    process.exitCode = 1;
    return;
  }
  const result = writeAssetVersions();
  if (result.fresh) {
    console.log(
      `asset versions already up to date (${result.versioned} references in ${result.files.length} files)`,
    );
  } else {
    console.log(`Wrote ${result.stale.length} file(s) with refreshed asset versions`);
    for (const line of result.summary) console.log(`  ${line}`);
  }
}

const invokedDirectly = (() => {
  try {
    return Boolean(process.argv[1]) && fs.realpathSync(process.argv[1]) === SCRIPT_PATH;
  } catch {
    return false;
  }
})();
if (invokedDirectly) main();
