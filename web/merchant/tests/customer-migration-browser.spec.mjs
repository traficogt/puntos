import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import express from 'express';
import helmet from 'helmet';
import { chromium } from 'playwright';
import { createSpanishWeb, createSpanishWebRedirects } from '../../../src/middleware/spanish-web.js';

const root = path.resolve(import.meta.dirname, '../../..');
const output = path.join(root, 'artifacts/customer-migration');
await fs.mkdir(output, { recursive: true });
const app = express();
app.use(helmet({ contentSecurityPolicy: { directives: { upgradeInsecureRequests: null } } }));
app.use(createSpanishWebRedirects()); app.use(createSpanishWeb(path.join(root, 'public'))); app.use(express.static(path.join(root, 'public')));
app.get('/runtime-config.js', (_req, res) => res.type('js').send('window.__PF_RUNTIME_CONFIG__={};'));
const server = app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const requests = [], errors = [];
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push(request.url()); });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/demostracion/#importar-clientes`);
  await page.getByRole('heading', { name: 'Importar clientes', exact: true }).waitFor();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Descargar plantilla CSV', exact: true }).click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(), 'plantilla-clientes-pf.csv');
  await page.getByRole('button', { name: 'Cargar muestra de clientes', exact: true }).click();
  await page.getByRole('heading', { name: 'Relaciona las columnas', exact: true }).waitFor();
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('button', { name: 'Resumen', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Relaciona las columnas', exact: true }).isVisible(), true);
  await page.getByRole('button', { name: 'Revisar lote', exact: true }).click();
  await page.getByRole('heading', { name: 'Revisa antes de importar', exact: true }).waitFor();
  const commit = page.getByRole('button', { name: 'Confirmar importación', exact: true });
  assert.equal(await commit.isDisabled(), true);
  await page.getByLabel('Nombre del lote', { exact: true }).fill('Clientes anteriores · prueba');
  await page.getByRole('checkbox', { name: /Revisé el archivo y confirmo importar/ }).check();
  assert.equal(await commit.isEnabled(), true);
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'review-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Tema oscuro', exact: true }).click();
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'review-mobile-dark.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const axe = await fs.readFile(path.join(root, 'web/merchant/node_modules/axe-core/axe.min.js'), 'utf8');
  await page.evaluate(axe);
  const violations = await page.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations);
  await fs.writeFile(path.join(output, 'axe-mobile.json'), JSON.stringify(violations, null, 2));
  assert.deepEqual(violations, []);
  await commit.click();
  await page.getByText('Importación de ejemplo guardada', { exact: true }).waitFor();
  await page.getByRole('cell', { name: 'Clientes anteriores · prueba', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Cargar muestra de clientes', exact: true }).click();
  await page.getByRole('button', { name: 'Revisar lote', exact: true }).click();
  assert.equal(await page.getByText('Ya existe', { exact: true }).count(), 2);
  await page.getByRole('combobox', { name: 'Si el teléfono ya existe en este negocio', exact: true }).click();
  await page.getByRole('option', { name: 'Rechazar el lote completo', exact: true }).click();
  assert.equal(await page.getByRole('heading', { name: 'Revisa antes de importar', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Revisar lote', exact: true }).click();
  await page.getByText('El lote necesita una corrección', { exact: true }).waitFor();
  assert.equal(await commit.isDisabled(), true);
  await page.locator('input[type=file]').setInputFiles({ name: 'duplicados.csv', mimeType: 'text/csv', buffer: Buffer.from('Teléfono,Nombre,Saldo\n55550003,Carla,12\n50255550003,Carla,18\n55550004,Dora,-1') });
  await page.getByRole('button', { name: 'Revisar lote', exact: true }).click();
  await page.getByText('Error', { exact: true }).first().waitFor();
  assert.equal(await page.getByText('Error', { exact: true }).count(), 3);
  assert.equal(await commit.isDisabled(), true);
  await page.reload();
  await page.getByRole('heading', { name: 'Importar clientes', exact: true }).waitFor();
  await page.getByText(/Todavía no hay lotes guardados/).waitFor();
  assert.deepEqual(requests, []);
  assert.deepEqual(errors, []);
  console.log('Migration browser: template, mapping, draft guard, explicit commit, existing policy, duplicate and invalid rows, reload isolation, mobile overflow and axe passed; zero real API requests.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
