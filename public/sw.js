function isCacheable(response) {
  const cacheControl = response.headers.get("Cache-Control") || "";
  const privateResponse = cacheControl
    .split(",")
    .some((directive) => /^\s*(?:private|no-store)\s*(?:=|$)/i.test(directive));
  return (
    response.ok && !privateResponse && (response.type === "basic" || response.type === "default")
  );
}

async function openCache() {
  return caches.open(CACHE);
}

async function precacheAsset(cache, asset) {
  const request = new Request(asset, { cache: "reload" });
  const response = await fetch(request);
  if (isCacheable(response)) {
    await cache.put(asset, response.clone());
  }
}

function cachedResponseFor(request, response) {
  // Precache follows canonical document redirects. Navigations use redirect
  // mode "manual", which rejects replaying that redirected response. Preserve
  // its document and security headers without replaying the redirect history.
  if (request.mode === "navigate" && response.redirected) {
    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers: response.headers,
    });
  }
  return response;
}

async function networkFirst(request, fallbackPath = "") {
  const cache = await openCache();

  try {
    const response = await fetch(request);
    if (isCacheable(response)) {
      await cache.put(request, response.clone());
    }
    return response;
  } catch {
    const cached = await cache.match(request);
    if (cached) return cachedResponseFor(request, cached);
    if (fallbackPath) {
      const fallback = await cache.match(fallbackPath);
      if (fallback) return cachedResponseFor(request, fallback);
    }
    throw new Error(`Offline and no cached asset for ${request.url}`);
  }
}

function fallbackForPath(pathname) {
  const normalizedPath =
    pathname.length > 1 && pathname.endsWith("/") ? pathname.slice(0, -1) : pathname;

  if (NAVIGATION_FALLBACKS.has(normalizedPath)) {
    return NAVIGATION_FALLBACKS.get(normalizedPath) || "";
  }
  if (/^\/(?:join|registro)\/[^/]+$/i.test(normalizedPath)) {
    return "/join.html";
  }
  if (/^\/ingresar\/[^/]+$/i.test(normalizedPath)) {
    return "/ingresar.html";
  }
  return "";
}

async function staleWhileRevalidate(request) {
  const cache = await openCache();
  const cached = await cache.match(request);

  const networkPromise = fetch(request)
    .then(async (response) => {
      if (isCacheable(response)) {
        await cache.put(request, response.clone());
      }
      return response;
    })
    .catch(() => null);

  return cached || networkPromise || fetch(request);
}

